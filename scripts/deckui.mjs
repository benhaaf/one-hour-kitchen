// Test der Präsentationssteuerung: Übersicht, Notizen, Referentenfenster. node scripts/deckui.mjs outdir
import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
const [,, out] = process.argv;
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 } });
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
await page.goto('file://' + process.cwd() + '/dist/index.html?debug');
await page.waitForTimeout(2500);
await page.keyboard.press('p');
await page.waitForTimeout(800);
for (let i = 0; i < 3; i++) await page.keyboard.press('PageDown');
await page.keyboard.press('n');
await page.evaluate(() => { const p = window.rille.presentation; if (p.flight) p.flight.t = 0.999; });
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/ui-notes.png`, timeout: 120000 });
console.log('index', await page.evaluate(() => window.rille.presentation.index));
await page.keyboard.press('o');
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/ui-overview.png`, timeout: 120000 });
await page.click('#deck-overview [data-i="18"]');
await page.waitForTimeout(500);
console.log('after click', await page.evaluate(() => window.rille.presentation.index));
const [pop] = await Promise.all([ctx.waitForEvent('page'), page.keyboard.press('v')]);
await pop.waitForLoadState();
pop.on('pageerror', (e) => console.log('POPERROR', e.message));
await pop.setViewportSize({ width: 1200, height: 720 });
await pop.waitForTimeout(2000);
await pop.keyboard.press('ArrowRight');
await pop.waitForTimeout(2500);
console.log('after popup next', await page.evaluate(() => window.rille.presentation.index));
await pop.screenshot({ path: `${out}/ui-referent.png`, timeout: 120000 });
await page.keyboard.press('Escape');
await page.waitForTimeout(500);
console.log('active after esc', await page.evaluate(() => window.rille.presentation.active));
await browser.close();
